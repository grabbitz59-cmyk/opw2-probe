package io.github.smartalarm

import android.view.View

/**
 * Одна из трёх страниц внутри [SectionsActivity].
 *
 * Зачем так: разделы приложения раньше были отдельными Activity, и их создание занимало
 * 183–551 мс (замерено на OPW2), причём создание шло в том же процессе и блокировало поток,
 * который рисует анимацию свайпа. Из-за этого переход «замирал и прыгал». Теперь все три
 * раздела — это View внутри одного окна: свайп двигает их напрямую, создания Activity нет.
 *
 * Страница строит свой `root` один раз (в конструкторе) и обновляет данные в [onShown] —
 * когда она становится текущей.
 */
abstract class SectionPage(protected val host: SectionsActivity) {

    /** Корень страницы: `FrameLayout` с прозрачным фоном, `MATCH_PARENT`. */
    abstract val root: View

    /** Страница стала текущей — перечитать данные. */
    open fun onShown() {}

    /** 1-based номер раздела (1 — будильник, 2 — ночь, 3 — статус). */
    open val section: Int get() = 0
}

/** Разделы приложения: 1 — будильник, 2 — ночь, 3 — статус. Листаются по кругу. */
object Sections {
    const val HOME = 1
    const val NIGHT = 2
    const val PULT = 3

    /** Следующий раздел по часовой стрелке (свайп влево): 1 → 2 → 3 → 1. */
    fun next(from: Int): Int = (from % 3) + 1

    /** Предыдущий раздел (свайп вправо): 1 → 3 → 2 → 1. */
    fun prev(from: Int): Int = ((from + 1) % 3) + 1
}
